#!/usr/bin/env node
// fwkit - Arduino firmware for a project.yaml project, through arduino-cli.
//
//   node fwkit.mjs pins    <project>                 write <sketch>/pins.h from project.yaml pins
//   node fwkit.mjs compile <project> [--json]        pins.h + compile + flash/RAM use + lint -> <sketch>/.fwkit/report.json
//   node fwkit.mjs status  <project>                 is the last compile current and passing?
//   node fwkit.mjs libs    <project>                 install firmware.libs
//   node fwkit.mjs ports                             connected boards
//   node fwkit.mjs upload  <project> [--port COM3]   compile, then upload (needs a current passing compile)
//   node fwkit.mjs monitor <project> [--port COM3] [--seconds 10]   read the serial output for a while
//
// <project> is the project folder (with project.yaml) or the file itself.
// Exit codes: 0 ok, 1 compile/upload failed or a FAIL, 2 usage / setup problem.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync, spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { load, resolveFile, normPin, loadBoard } from '../../project/projkit/projkit.mjs';
import { loadConfig } from '../../cad-validation/cadkit/config.mjs';

const SRC_EXT = ['.ino', '.h', '.hpp', '.c', '.cpp'];
const isNone = (v) => v === undefined || v === null || v === 'none' || (Array.isArray(v) && v.length === 0);
const list = (v) => (isNone(v) ? [] : Array.isArray(v) ? v : [v]);
const str = (v) => (v === undefined || v === null ? '' : String(v).trim());

export function project(arg) {
  const file = resolveFile(arg);
  if (!file || !fs.existsSync(file)) throw new Setup(`no project.yaml at ${arg}`);
  const p = load(file);
  const fw = p.firmware || {};
  if (isNone(fw.fqbn)) throw new Setup('firmware.fqbn is none in project.yaml (e.g. arduino:avr:uno)');
  if (isNone(fw.sketch)) throw new Setup('firmware.sketch is none in project.yaml (e.g. firmware/my-project)');
  const sketch = path.resolve(path.dirname(file), str(fw.sketch));
  const ctrl = list(p.components).find((c) => str(c.id) === str(p.controller));
  const board = ctrl && ctrl.board ? loadBoard(str(ctrl.board)) : null;
  return { file, p, fw, sketch, fqbn: str(fw.fqbn), board, baud: Number(fw.baud) || 115200 };
}
class Setup extends Error {}

function cli() {
  const c = loadConfig().arduino_cli;
  if (!c || !fs.existsSync(c)) throw new Setup('arduino-cli not found: install it, or set arduino_cli in the cadkit config (Arduino IDE 2 ships one)');
  return c;
}
const run = (args, opts = {}) => spawnSync(cli(), args, { encoding: 'utf8', maxBuffer: 1 << 26, ...opts });

// ---------------------------------------------------------------------------
// pins.h: one constant per signal pin, so the code can never disagree with the wiring
const ident = (s) => str(s).toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '');
export function pinsHeader(P) {
  const { p, board } = P;
  const lines = ['// Generated by fwkit from project.yaml - do not edit, regenerate: node fwkit.mjs pins <project>',
    `// Project: ${str(p.title) || p.project}  Board: ${board ? board.id : 'unknown'}`, '#pragma once', '#include <Arduino.h>', ''];
  const i2c = [];
  for (const e of list(p.pins)) {
    const pin = normPin(e.pin), to = str(e.to);
    if (board && board.power_pins && board.power_pins[pin]) continue;
    if (['GND', '5V', '3V3', 'VIN'].includes(pin)) continue;
    const [cid, sig] = to.split('.');
    if (['sda', 'scl'].includes(str(sig).toLowerCase())) { i2c.push(`//   ${to} on ${pin} (Wire uses it by default)`); continue; }
    const val = /^D\d+$/.test(pin) ? pin.slice(1) : /^GPIO\d+$/.test(pin) ? pin.slice(4) : pin; // A0 stays A0
    lines.push(`constexpr uint8_t PIN_${ident(cid)}_${ident(sig)} = ${val};   // ${pin} -> ${to}`);
  }
  if (i2c.length) lines.push('', '// I2C:', ...i2c);
  const addrs = list(p.components).filter((c) => !isNone(c.i2c_addr));
  if (addrs.length) {
    lines.push('');
    for (const c of addrs) {
      const a = list(c.i2c_addr)[0];
      lines.push(`constexpr uint8_t I2C_ADDR_${ident(c.id)} = ${typeof a === 'number' ? '0x' + a.toString(16).toUpperCase() : str(a)};`);
    }
  }
  lines.push('', `constexpr unsigned long SERIAL_BAUD = ${P.baud};`, '');
  return lines.join('\n');
}
function writePins(P) {
  fs.mkdirSync(P.sketch, { recursive: true });
  const f = path.join(P.sketch, 'pins.h'), txt = pinsHeader(P);
  // compare without line endings: a git checkout on Windows turns LF into CRLF
  const old = fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') : null;
  if (old !== txt) fs.writeFileSync(f, txt);
  return { file: f, changed: old !== txt };
}

// ---------------------------------------------------------------------------
function sources(dir) {
  const out = [];
  const walk = (d) => {
    for (const n of fs.readdirSync(d, { withFileTypes: true })) {
      if (n.name.startsWith('.') || n.name === 'build') continue;
      const f = path.join(d, n.name);
      if (n.isDirectory()) walk(f); else if (SRC_EXT.includes(path.extname(n.name).toLowerCase())) out.push(f);
    }
  };
  if (fs.existsSync(dir)) walk(dir);
  return out.sort();
}
function stamp(P) {
  const h = createHash('sha256');
  h.update(P.fqbn);
  for (const f of sources(P.sketch)) { h.update(path.relative(P.sketch, f)); h.update(fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n')); }
  return h.digest('hex').slice(0, 16);
}
const reportFile = (P) => path.join(P.sketch, '.fwkit', 'report.json');

// things the compiler does not catch
export function lint(P) {
  const out = [];
  const src = sources(P.sketch).filter((f) => path.basename(f) !== 'pins.h');
  for (const f of src) {
    const txt = fs.readFileSync(f, 'utf8');
    const rel = path.relative(P.sketch, f);
    txt.split(/\r?\n/).forEach((line, i) => {
      const code = line.replace(/\/\/.*$/, '');
      const m = code.match(/\b(pinMode|digitalWrite|digitalRead|analogWrite|analogRead|tone|attachInterrupt)\s*\(\s*(A?\d+)\s*[,)]/);
      if (m) out.push({ level: 'WARNING', msg: `${rel}:${i + 1}: ${m[1]}(${m[2]}) uses a literal pin: use the PIN_* constant from pins.h so code and wiring stay the same` });
      const b = code.match(/Serial\.begin\s*\(\s*(\d+)/);
      if (b && Number(b[1]) !== P.baud) out.push({ level: 'WARNING', msg: `${rel}:${i + 1}: Serial.begin(${b[1]}) but firmware.baud is ${P.baud}: the monitor will show garbage (use SERIAL_BAUD)` });
      if (/\bdelay\s*\(\s*\d{4,}\s*\)/.test(code) && /loop|button|sensor/i.test(txt)) out.push({ level: 'INFO', msg: `${rel}:${i + 1}: a long delay() blocks buttons and sensors meanwhile; millis() timing may be needed` });
    });
  }
  if (src.length && !src.some((f) => /#include\s+["<]pins\.h[">]/.test(fs.readFileSync(f, 'utf8')))) out.push({ level: 'WARNING', msg: 'no source includes "pins.h": pin numbers are not tied to project.yaml' });
  const ino = path.join(P.sketch, path.basename(P.sketch) + '.ino');
  if (!fs.existsSync(ino)) out.push({ level: 'FAIL', msg: `arduino-cli needs ${path.basename(P.sketch)}.ino inside the sketch folder (folder name = sketch name)` });
  return out;
}

export function compile(P) {
  const pins = writePins(P);
  const issues = lint(P);
  const res = { project: P.p.project, fqbn: P.fqbn, sketch: P.sketch, stamp: null, ok: false, when: new Date().toISOString(), usage: {}, issues, errors: '' };
  if (issues.some((x) => x.level === 'FAIL')) { res.stamp = stamp(P); return save(P, res); }
  const r = run(['compile', '--fqbn', P.fqbn, '--build-path', path.join(P.sketch, '.fwkit', 'build'), '--warnings', 'default', '--format', 'json', P.sketch]);
  let j = {};
  try { j = JSON.parse(r.stdout); } catch { j = { success: false, compiler_err: r.stdout + r.stderr }; }
  res.ok = j.success === true || (j.success === undefined && r.status === 0);
  res.errors = str(j.compiler_err || (res.ok ? '' : r.stderr || j.error));
  for (const s of (j.builder_result && j.builder_result.executable_sections_size) || []) {
    res.usage[s.name === 'text' ? 'flash' : s.name === 'data' ? 'ram' : s.name] = { used: s.size, max: s.max_size, pct: s.max_size ? Math.round((100 * s.size) / s.max_size) : null };
  }
  const ram = res.usage.ram;
  if (ram && ram.pct >= 75) issues.push({ level: 'WARNING', msg: `RAM ${ram.pct} % used by globals: above ~75 % an AVR board gets random crashes (use F("...") for strings)` });
  const fl = res.usage.flash;
  if (fl && fl.pct >= 95) issues.push({ level: 'WARNING', msg: `flash ${fl.pct} % full` });
  const warnLines = str(j.compiler_err).split(/\r?\n/).filter((l) => /warning:/.test(l) && l.includes(P.sketch.replace(/\\/g, '/').split('/').pop()));
  for (const l of warnLines.slice(0, 10)) issues.push({ level: 'WARNING', msg: `compiler: ${l.replace(/^.*?([^\\/]+:\d+:\d+: warning:)/, '$1')}` });
  res.stamp = stamp(P);
  res.pins_regenerated = pins.changed;
  return save(P, res);
}
function save(P, res) {
  fs.mkdirSync(path.dirname(reportFile(P)), { recursive: true });
  fs.writeFileSync(reportFile(P), JSON.stringify(res, null, 2));
  return res;
}
export function status(P) {
  const f = reportFile(P);
  if (!fs.existsSync(f)) return { current: false, ok: false, why: 'never compiled' };
  const r = JSON.parse(fs.readFileSync(f, 'utf8'));
  const pinsStale = !fs.existsSync(path.join(P.sketch, 'pins.h')) || fs.readFileSync(path.join(P.sketch, 'pins.h'), 'utf8').replace(/\r\n/g, '\n') !== pinsHeader(P);
  const cur = r.stamp === stamp(P) && !pinsStale;
  return { current: cur, ok: r.ok && cur, report: r, why: !cur ? (pinsStale ? 'project.yaml pins changed since pins.h was written' : 'sources changed since the last compile') : r.ok ? 'compiled OK' : 'last compile failed' };
}

// ---------------------------------------------------------------------------
function ports(fqbn) {
  const r = run(['board', 'list', '--format', 'json']);
  let j = [];
  try { j = JSON.parse(r.stdout); } catch { return []; }
  const rows = Array.isArray(j) ? j : j.detected_ports || [];
  return rows.map((d) => ({
    port: d.port && d.port.address, protocol: d.port && d.port.protocol,
    boards: (d.matching_boards || []).map((b) => b.fqbn), usb: !!(d.port && d.port.properties && d.port.properties.vid),
  })).filter((x) => x.port && x.protocol === 'serial');
}
function pickPort(P, given) {
  if (typeof given === 'string') return given;
  if (!isNone(P.fw.port) && str(P.fw.port) !== 'auto') return str(P.fw.port);
  const all = ports(P.fqbn);
  const exact = all.filter((x) => x.boards.includes(P.fqbn));
  if (exact.length === 1) return exact[0].port;
  const usb = all.filter((x) => x.usb);
  if (usb.length === 1) return usb[0].port; // clones with a CH340 are not identified by name
  throw new Setup(usb.length ? `several boards connected (${usb.map((x) => x.port).join(', ')}): pass --port` : `no board found (ports: ${all.map((x) => x.port).join(', ') || 'none'}). Plug it in, check the USB cable carries data, CH340 clones need a driver`);
}

function printRes(res) {
  const u = res.usage;
  console.log(`${res.ok ? 'COMPILED' : 'COMPILE FAILED'}  ${res.fqbn}  ${res.sketch}`);
  if (u.flash) console.log(`flash ${u.flash.used}/${u.flash.max} bytes (${u.flash.pct} %)`);
  if (u.ram) console.log(`RAM   ${u.ram.used}/${u.ram.max} bytes (${u.ram.pct} %)`);
  for (const x of res.issues) console.log(`${x.level.padEnd(8)} ${x.msg}`);
  if (!res.ok && res.errors) console.log('\n' + res.errors.split(/\r?\n/).filter((l) => /error|Error|fatal/.test(l)).slice(0, 25).join('\n'));
}

async function main() {
  const [cmd, arg, ...rest] = process.argv.slice(2);
  const flag = (f) => { const i = rest.indexOf(f); return i >= 0 ? rest[i + 1] ?? true : null; };
  try {
    if (cmd === 'pins') { const P = project(arg); const w = writePins(P); console.log(`${w.changed ? 'wrote' : 'unchanged'} ${w.file}`); }
    else if (cmd === 'compile') { const res = compile(project(arg)); if (rest.includes('--json')) console.log(JSON.stringify(res, null, 2)); else printRes(res); process.exit(res.ok && !res.issues.some((x) => x.level === 'FAIL') ? 0 : 1); }
    else if (cmd === 'status') { const s = status(project(arg)); console.log(`${s.ok ? 'OK' : 'NOT OK'}: ${s.why}`); process.exit(s.ok ? 0 : 1); }
    else if (cmd === 'libs') {
      const P = project(arg); const libs = list(P.fw.libs).map(str);
      if (!libs.length) { console.log('firmware.libs is empty'); return; }
      for (const l of libs) { const r = run(['lib', 'install', l]); console.log(`${r.status === 0 ? 'ok  ' : 'FAIL'} ${l}${r.status === 0 ? '' : ': ' + str(r.stderr || r.stdout)}`); if (r.status !== 0) process.exitCode = 1; }
    }
    else if (cmd === 'ports') { for (const x of ports()) console.log(`${x.port.padEnd(8)} ${x.usb ? 'USB' : '   '} ${x.boards.join(', ') || '(not identified)'}`); }
    else if (cmd === 'upload') {
      const P = project(arg);
      const res = compile(P);
      if (!res.ok) { printRes(res); console.log('\nnot uploaded: the compile failed'); process.exit(1); }
      const port = pickPort(P, flag('--port'));
      const r = run(['upload', '-p', port, '--fqbn', P.fqbn, '--input-dir', path.join(P.sketch, '.fwkit', 'build'), P.sketch]);
      console.log(r.status === 0 ? `UPLOADED to ${port}` : `UPLOAD FAILED on ${port}:\n${str(r.stderr || r.stdout)}\n(old-bootloader Nano clones need fqbn arduino:avr:nano:cpu=atmega328old; close any open serial monitor)`);
      process.exit(r.status === 0 ? 0 : 1);
    }
    else if (cmd === 'monitor') {
      const P = project(arg);
      const port = pickPort(P, flag('--port'));
      const secs = Number(flag('--seconds')) || 10;
      const child = spawn(cli(), ['monitor', '-p', port, '--config', `baudrate=${P.baud}`, '--quiet'], { stdio: ['pipe', 'pipe', 'pipe'] });
      let out = '';
      child.stdout.on('data', (d) => { out += d; process.stdout.write(d); });
      child.stderr.on('data', (d) => { out += d; });
      await new Promise((ok) => setTimeout(ok, secs * 1000));
      child.kill();
      if (!out.trim()) console.log(`(nothing in ${secs} s at ${P.baud} baud on ${port}: is the sketch printing, is the baud right, did it reset?)`);
    }
    else {
      console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 13).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
      process.exit(cmd ? 2 : 0);
    }
  } catch (e) {
    if (e instanceof Setup) { console.error(e.message); process.exit(2); }
    throw e;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
